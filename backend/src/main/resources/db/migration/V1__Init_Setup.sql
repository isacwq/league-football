CREATE TABLE clubes
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome      VARCHAR(60)                             NOT NULL,
    sigla     VARCHAR(3)                              NOT NULL,
    caixa     DECIMAL(12, 2)                          NOT NULL,
    formacao  VARCHAR(10),
    criado_em TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_clubes PRIMARY KEY (id)
);

CREATE TABLE contratos
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    jogador_id     BIGINT                                  NOT NULL,
    clube_id       BIGINT                                  NOT NULL,
    valor_compra   DECIMAL(12, 2)                          NOT NULL,
    fidelidade_ate TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    status         VARCHAR(20)                             NOT NULL,
    inicio_em      TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    fim_em         TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_contratos PRIMARY KEY (id)
);

CREATE TABLE duelos
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    partida_id        BIGINT                                  NOT NULL,
    ordem             INTEGER                                 NOT NULL,
    clube_atacante_id BIGINT                                  NOT NULL,
    atacante_id       BIGINT                                  NOT NULL,
    defensor_id       BIGINT                                  NOT NULL,
    nome_atacante     VARCHAR(100)                            NOT NULL,
    nome_defensor     VARCHAR(100)                            NOT NULL,
    posicao_atacante  VARCHAR(10)                             NOT NULL,
    posicao_defensor  VARCHAR(10)                             NOT NULL,
    condicao_atacante VARCHAR(20)                             NOT NULL,
    condicao_defensor VARCHAR(20)                             NOT NULL,
    atributo_ataque   VARCHAR(20)                             NOT NULL,
    atributo_defesa   VARCHAR(20)                             NOT NULL,
    valor_ataque      INTEGER                                 NOT NULL,
    valor_defesa      INTEGER                                 NOT NULL,
    gol               BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_duelos PRIMARY KEY (id)
);

CREATE TABLE escalacoes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    clube_id   BIGINT                                  NOT NULL,
    jogador_id BIGINT                                  NOT NULL,
    criado_em  TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_escalacoes PRIMARY KEY (id)
);

CREATE TABLE jogadores
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome        VARCHAR(100)                            NOT NULL,
    posicao     VARCHAR(10)                             NOT NULL,
    agilidade   INTEGER                                 NOT NULL,
    idade       INTEGER                                 NOT NULL,
    ritmo       INTEGER                                 NOT NULL,
    chute       INTEGER                                 NOT NULL,
    passe       INTEGER                                 NOT NULL,
    driblar     INTEGER                                 NOT NULL,
    defesa      INTEGER                                 NOT NULL,
    fisico      INTEGER                                 NOT NULL,
    potencial   INTEGER                                 NOT NULL,
    valor_base  DECIMAL(12, 2)                          NOT NULL,
    condicao    VARCHAR(20)                             NOT NULL,
    clube_id    BIGINT,
    excluido_em TIMESTAMP WITHOUT TIME ZONE,
    criado_em   TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_jogadores PRIMARY KEY (id)
);

CREATE TABLE partidas
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    clube_mandante_id  BIGINT                                  NOT NULL,
    clube_visitante_id BIGINT                                  NOT NULL,
    gols_mandante      INTEGER                                 NOT NULL,
    gols_visitante     INTEGER                                 NOT NULL,
    formacao_mandante  VARCHAR(10)                             NOT NULL,
    formacao_visitante VARCHAR(10)                             NOT NULL,
    resultado          VARCHAR(15)                             NOT NULL,
    realizada_em       TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_partidas PRIMARY KEY (id)
);

CREATE TABLE transacoes
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    clube_id         BIGINT                                  NOT NULL,
    jogador_id       BIGINT                                  NOT NULL,
    nome_jogador     VARCHAR(100)                            NOT NULL,
    tipo             VARCHAR(10)                             NOT NULL,
    valor            DECIMAL(12, 2)                          NOT NULL,
    taxa_ou_comissao DECIMAL(12, 2)                          NOT NULL,
    multa            DECIMAL(12, 2)                          NOT NULL,
    lucro            DECIMAL(12, 2),
    variacao_caixa   DECIMAL(12, 2)                          NOT NULL,
    criado_em        TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_transacoes PRIMARY KEY (id)
);

